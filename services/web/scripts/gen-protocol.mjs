// Generates src/live/protocol.gen.ts from src/live/protocol.schema.json, which Django writes
// (`manage.py export_ws_schema`). `--check` fails instead of writing when the file is out of date.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = resolve(root, "src/live/protocol.schema.json");
const outPath = resolve(root, "src/live/protocol.gen.ts");

const banner = `/* Generated by \`npm run gen\` from protocol.schema.json. Do not edit by hand.
 * The schema comes from the Django side: \`manage.py export_ws_schema\`. */`;

const schema = JSON.parse(await readFile(schemaPath, "utf8"));
const generated = await compile(schema, "LiveProtocol", {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  strictIndexSignatures: true,
  enableConstEnums: false,
  style: { printWidth: 100, singleQuote: false, trailingComma: "all" },
});

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = await readFile(outPath, "utf8");
  } catch {
    // Missing counts as out of date.
  }
  if (current !== generated) {
    console.error("src/live/protocol.gen.ts is out of date. Run `npm run gen`.");
    process.exit(1);
  }
  console.log("protocol.gen.ts is up to date.");
} else {
  await writeFile(outPath, generated);
  console.log("Wrote src/live/protocol.gen.ts");
}
